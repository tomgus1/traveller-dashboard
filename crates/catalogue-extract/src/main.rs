//! Extracts equipment tables from a Traveller rulebook PDF the group owns
//! into a private catalogue JSON file.
//!
//! ```sh
//! cargo run -p catalogue-extract -- csc-2023 "books/<CSC 2023>.pdf" data/catalogue/csc-2023.json 2> report.txt
//! ```
//!
//! Then a script that loads catalogue files into the database (migration
//! 10's `load_catalogue`), to run in Supabase's SQL editor or with psql:
//!
//! ```sh
//! cargo run -p catalogue-extract -- sql data/catalogue/*.json > data/catalogue/load.sql
//! ```
//!
//! Both are copyrighted data: keep them in the git-ignored
//! `data/catalogue/`. Extracting needs poppler's `pdftotext`.

mod items;
mod tables;
mod words;

use std::collections::BTreeMap;
use std::path::Path;
use std::process::ExitCode;

use traveller_model::catalogue::Catalogue;

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.first().map(String::as_str) == Some("sql") && args.len() > 1 {
        return match load_script(&args[1..]) {
            Ok(script) => {
                print!("{script}");
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("{e}");
                ExitCode::FAILURE
            }
        };
    }
    let [book_id, pdf, out] = args.as_slice() else {
        let known: Vec<&str> = items::BOOKS.iter().map(|b| b.id).collect();
        eprintln!(
            "usage: catalogue-extract <book> <pdf> <out.json>\n       catalogue-extract sql <catalogue.json>... > load.sql\n  books: {}",
            known.join(", ")
        );
        return ExitCode::FAILURE;
    };
    let Some(book) = items::BOOKS.iter().find(|b| b.id == book_id) else {
        eprintln!("unknown book {book_id}");
        return ExitCode::FAILURE;
    };

    let pages = match words::read_pdf(Path::new(pdf)) {
        Ok(p) => p,
        Err(e) => {
            eprintln!("{e}");
            return ExitCode::FAILURE;
        }
    };
    let (first, last) = book.pages;
    let tables: Vec<tables::RawTable> = pages
        .iter()
        .filter(|p| {
            let printed = p.number.saturating_sub(book.page_offset);
            (first..=last).contains(&printed)
        })
        .flat_map(|p| tables::find_tables(p.number, p.width, &p.words))
        .collect();
    let items = items::items(book, &tables);

    // A report to review: counts, and rows that look incomplete.
    let mut by_section: BTreeMap<&str, usize> = BTreeMap::new();
    for item in &items {
        *by_section.entry(&item.section).or_default() += 1;
    }
    eprintln!(
        "{} tables, {} items from {}",
        tables.len(),
        items.len(),
        book.title
    );
    for (section, n) in &by_section {
        eprintln!("  {n:4}  {section}");
    }
    let suspect: Vec<_> = items
        .iter()
        .filter(|i| {
            i.tl.is_none()
                || (i.cost.is_none() && !i.columns.get("COST").is_some_and(|c| c.contains('—')))
        })
        .collect();
    eprintln!("{} items to check (no TL, or no price):", suspect.len());
    for item in suspect.iter().take(60) {
        eprintln!("  p.{:<3} {}  {:?}", item.page, item.name, item.columns);
    }

    write_catalogue(book, items, out)
}

fn write_catalogue(
    book: &items::Book,
    items: Vec<traveller_model::catalogue::CatalogueItem>,
    out: &str,
) -> ExitCode {
    let catalogue = Catalogue {
        book: book.id.to_string(),
        title: book.title.to_string(),
        items,
    };
    match serde_json::to_string_pretty(&catalogue)
        .map_err(|e| e.to_string())
        .and_then(|json| std::fs::write(out, json + "\n").map_err(|e| e.to_string()))
    {
        Ok(()) => {
            eprintln!("wrote {out}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("couldn't write {out}: {e}");
            ExitCode::FAILURE
        }
    }
}

/// Quotes the catalogue JSON in the load script.
const QUOTE: &str = "$catalogue$";

/// A SQL script that loads each catalogue file with `load_catalogue`, in
/// one transaction.
fn load_script(paths: &[String]) -> Result<String, String> {
    let mut script = String::from(
        "-- Loads the equipment catalogue (migration 10). Generated by\n\
         -- catalogue-extract. Copyrighted book data: don't commit or share.\n\
         BEGIN;\n",
    );
    for path in paths {
        let text =
            std::fs::read_to_string(path).map_err(|e| format!("couldn't read {path}: {e}"))?;
        script.push_str(&load_statement(&text).map_err(|e| format!("{path}: {e}"))?);
    }
    script.push_str("COMMIT;\n");
    Ok(script)
}

/// One book's `SELECT public.load_catalogue(…)`, checking the file is a
/// catalogue first.
fn load_statement(json: &str) -> Result<String, String> {
    let catalogue: Catalogue =
        serde_json::from_str(json).map_err(|e| format!("not a catalogue file: {e}"))?;
    let compact = serde_json::to_string(&catalogue).map_err(|e| e.to_string())?;
    if compact.contains(QUOTE) {
        return Err(format!(
            "the data contains {QUOTE}, which the script uses as a quote"
        ));
    }
    Ok(format!(
        "SELECT public.load_catalogue({QUOTE}{compact}{QUOTE}::jsonb) AS \"{} items\";\n",
        catalogue.book.replace('"', "")
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn load_statements_quote_the_catalogue() {
        let sql = load_statement(r#"{"book":"test","title":"Test","items":[]}"#).unwrap();
        assert_eq!(
            sql,
            "SELECT public.load_catalogue($catalogue${\"book\":\"test\",\"title\":\"Test\",\"items\":[]}$catalogue$::jsonb) AS \"test items\";\n"
        );
        assert!(load_statement(r#"{"nope":1}"#).is_err());
        assert!(
            load_statement(r#"{"book":"t","title":"$catalogue$","items":[]}"#).is_err(),
            "the quote can't appear in the data"
        );
    }
}
